struct Handle {
  tr_tensor* t;
  explicit Handle(tr_tensor* p) : t(p) {}
  Handle(const Handle&) = delete;
  Handle& operator=(const Handle&) = delete;
  ~Handle() {
    tr_tensor_free(t);
  }
};

tr_tensor* decode(const std::vector<uint8_t>& bytes, int32_t channels) {
  return tr_image_decode(bytes.data(), static_cast<int64_t>(bytes.size()),
                         channels);
}

std::vector<int64_t> shape_of(const tr_tensor* t) {
  int64_t ndim = 0;
  EXPECT_EQ(tr_tensor_ndim(t, &ndim), 0) << tr_last_error();
  std::vector<int64_t> dims(static_cast<size_t>(ndim));
  int64_t got = 0;
  EXPECT_EQ(tr_tensor_shape(t, ndim, dims.data(), &got), 0) << tr_last_error();
  return dims;
}

std::vector<uint8_t> bytes_of(const tr_tensor* t) {
  int64_t numel = 0;
  EXPECT_EQ(tr_tensor_numel(t, &numel), 0) << tr_last_error();
  std::vector<uint8_t> out(static_cast<size_t>(numel));
  uint64_t got = 0;
  EXPECT_EQ(tr_tensor_copy_data_u8(t, out.size(), out.data(), &got), 0)
      << tr_last_error();
  return out;
}

TEST(ImageDecode, PngComesBackChannelsFirstExactly) {
  const Handle img(decode(kPngRgb3x2, 0));
  ASSERT_NE(img.t, nullptr) << tr_last_error();
  EXPECT_EQ(shape_of(img.t), (std::vector<int64_t>{3, 2, 3}));
  tr_dtype dtype{};
  ASSERT_EQ(tr_tensor_dtype(img.t, &dtype), 0);
  EXPECT_EQ(dtype, TR_DTYPE_UINT8);
  EXPECT_EQ(bytes_of(img.t),
            (std::vector<uint8_t>{255, 0, 0, 10, 40, 70, 0, 255, 0, 20, 50, 80,
                                  0, 0, 255, 30, 60, 90}));
}

TEST(ImageDecode, RequestedChannelsConvert) {
  const Handle rgba(decode(kPngRgb3x2, 4));
  ASSERT_NE(rgba.t, nullptr) << tr_last_error();
  EXPECT_EQ(shape_of(rgba.t), (std::vector<int64_t>{4, 2, 3}));
  const std::vector<uint8_t> px = bytes_of(rgba.t);
  EXPECT_EQ(std::vector<uint8_t>(px.begin() + 18, px.end()),
            std::vector<uint8_t>(6, 255));
  const Handle gray(decode(kPngRgb3x2, 1));
  ASSERT_NE(gray.t, nullptr) << tr_last_error();
  EXPECT_EQ(shape_of(gray.t), (std::vector<int64_t>{1, 2, 3}));
}

TEST(ImageDecode, SolidJpegDecodesToItsValue) {
  const Handle img(decode(kJpegGray8x8, 0));
  ASSERT_NE(img.t, nullptr) << tr_last_error();
  EXPECT_EQ(shape_of(img.t), (std::vector<int64_t>{1, 8, 8}));
  EXPECT_EQ(bytes_of(img.t), std::vector<uint8_t>(64, 100));
  const Handle rgb(decode(kJpegGray8x8, 3));
  ASSERT_NE(rgb.t, nullptr) << tr_last_error();
  EXPECT_EQ(shape_of(rgb.t), (std::vector<int64_t>{3, 8, 8}));
  EXPECT_EQ(bytes_of(rgb.t), std::vector<uint8_t>(192, 100));
}

TEST(ImageDecode, FailuresAreStatusNotAborts) {
  const std::vector<uint8_t> junk = {'n', 'o', 't', ' ', 'a', 'n', ' ', 'i'};
  EXPECT_EQ(decode(junk, 0), nullptr);
  EXPECT_NE(std::string(tr_last_error()).find("cannot decode image"),
            std::string::npos)
      << tr_last_error();
  const std::vector<uint8_t> truncated(kPngRgb3x2.begin(),
                                       kPngRgb3x2.begin() + 40);
  EXPECT_EQ(decode(truncated, 0), nullptr);
  EXPECT_EQ(decode(kPngRgb3x2, 5), nullptr);
  EXPECT_NE(std::string(tr_last_error()).find("channels"), std::string::npos);
  EXPECT_EQ(tr_image_decode(kPngRgb3x2.data(), 0, 0), nullptr);
  EXPECT_EQ(tr_image_decode(nullptr, 8, 0), nullptr);
  EXPECT_NE(std::string(tr_last_error()).find("null argument"),
            std::string::npos);
}

